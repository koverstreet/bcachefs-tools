/// Size of a bpos in bytes — maximum size of any accounting key payload.
const BPOS_SIZE: usize = core::mem::size_of::<Bpos>();

/// A bpos is one integer in native byte order, and a disk_accounting_pos the
/// same integer big-endian - so its first byte, the inode's top one, is the
/// type: memcpy_swab() on little endian, a copy on big.
fn memcpy_swab_le(dst: &mut [u8], src: &[u8]) {
    dst.copy_from_slice(src);
    if cfg!(target_endian = "little") {
        dst.reverse();
    }
}

impl DiskAccountingPos<Unvalidated> {
    pub fn from_bpos(p: Bpos) -> Self {
        let mut b = [0u8; BPOS_SIZE];
        memcpy_swab_le(&mut b, plain_bytes(&p));
        Self::from_bytes(&b)
    }
}

impl<S> DiskAccountingPos<S> {
    pub fn to_bpos(&self) -> Bpos {
        let mut p = Bpos::default();
        memcpy_swab_le(plain_bytes_mut(&mut p), self.as_bytes());
        p
    }

    pub fn nr_counters(&self) -> usize {
        TYPE_NR_COUNTERS[self.type_().0 as usize]
    }

    pub(crate) fn next_type_start(&self) -> Bpos {
        let mut next = [0u8; BPOS_SIZE];
        next[0] = self.type_().0 as u8 + 1;
        DiskAccountingPos::from_bytes(&next).to_bpos()
    }
}

impl DevDataType {
    /// Its data type, if this version knows it: a newer version's are kept
    /// in the table, but not in a device's usage, which has no slot for them.
    pub fn known_data_type(&self) -> Option<DataType> {
        let t = DataType(self.data_type.into());
        (t.0 < DataType::nr.0).then_some(t)
    }
}

pub(crate) fn replicas_entry(pos: &DiskAccountingPos<Unvalidated>) -> Option<&c::bch_replicas_entry_v1> {
    match pos.validated().ok()?.get() {
        Ok(DiskAccountingPosRef::replicas(r)) => Some(r),
        _ => None,
    }
}

pub fn is_mem<S>(pos: &DiskAccountingPos<S>) -> bool {
    let t = pos.type_();
    (t.0 as usize) < TYPE_NR && t != disk_accounting_type::BCH_DISK_ACCOUNTING_inum
}

const TYPE_NR: usize = disk_accounting_type::BCH_DISK_ACCOUNTING_TYPE_NR.0 as usize;

macro_rules! type_nr_counters {
    ($(($t:ident, $id:expr)),* $(,)?) => { ::paste::paste! {{
        let mut a = [0; TYPE_NR];
        $(a[$id] = [<$t:camel Counters>]::NR;)*
        a
    }}};
}

const TYPE_NR_COUNTERS: [usize; TYPE_NR] = BCH_DISK_ACCOUNTING_TYPES!(type_nr_counters);

pub const MAX_COUNTERS: usize = BCH_ACCOUNTING_MAX_COUNTERS as usize;
pub type Counters = [u64; MAX_COUNTERS];

pub trait KeyType: ArmOf<DiskAccountingPos__ffi, Tag = u8> + Copy {
    type Delta: CounterSet<i64>;
    type Read:  CounterSet<u64>;
}

pub trait CounterSet<T>: Copy {
    fn from_slice(d: &[T]) -> Self;
    fn with_slice<R>(self, f: impl FnOnce(&[T]) -> R) -> R;
}

macro_rules! acct_counters {
    ($name:ident { $($f:ident),+ }) => {
        #[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
        pub struct $name<T = u64> { $(pub $f: T),+ }

        impl<T> $name<T> {
            pub fn map<U>(self, mut f: impl FnMut(T) -> U) -> $name<U> {
                $name { $($f: f(self.$f)),+ }
            }
        }

        impl<T: Copy + Default> $crate::accounting::CounterSet<T> for $name<T> {
            fn from_slice(d: &[T]) -> Self {
                let mut d = d.iter().copied();
                Self { $($f: d.next().unwrap_or_default()),+ }
            }

            fn with_slice<R>(self, f: impl FnOnce(&[T]) -> R) -> R {
                f(&[$(self.$f),+])
            }
        }

        impl $name {
            pub const NR: usize = [$(stringify!($f)),+].len();
        }
    };
}
pub(crate) use acct_counters;

pub(crate) fn accounting_bkey(p: Bpos, nr_counters: usize) -> format::bkey {
    let mut k = format::bkey { type_: <Accounting as BkeyTag>::TYPE.0 as u8, p, ..format::bkey::new() };
    k.set_val_bytes(nr_counters * size_of::<u64>());
    k
}

/* @acc's replicas entry has more devs than the key has room for: */
fn replicas_past_end(err: VStructError) -> Option<(usize, usize)> {
    let hdr = size_of::<Head<c::bch_replicas_entry_v1>>();
    match err {
        VStructError::Overrun { want, have, .. } => Some((want - hdr, have - hdr)),
        _ => None,
    }
}

#[cold]
pub fn key_to_text(out: &mut Printbuf, fs: Option<&Fs>, pos: &DiskAccountingPos<Unvalidated>) {
    use DiskAccountingPosRef as A;

    let arm = match pos.get() {
        Err(ArmError::Unknown(t)) => {
            write!(out, "unknown type {}", t.0);
            return;
        }
        arm => arm,
    };

    write!(out, "{} ", pos.type_());

    match arm {
        Err(ArmError::Bad { err, .. }) => match replicas_past_end(err) {
            Some((devs, _)) => write!(out, "(replicas entry with {devs} devs runs past the end of the key)"),
            None => write!(out, "(replicas entry: {err})"),
        },
        Err(_) => {}
        Ok(A::persistent_reserved(a)) => write!(out, "replicas={}", a.nr_replicas),
        Ok(A::replicas(r)) => SbEntry::from(r).to_text(out),
        Ok(A::dev_data_type(a)) => write!(out, "dev={} data_type={}", a.dev, DataType(a.data_type.into())),
        Ok(A::compression(a)) => write!(out, "{}", CompressionType(a.type_.into())),
        Ok(A::snapshot(a)) => {
            let (id, btree) = (a.id, format::Btree(a.btree));
            write!(out, "id={id} btree={btree}");
        }
        Ok(A::btree(a)) => {
            let btree = format::Btree(a.id);
            write!(out, "btree={btree}");
        }
        Ok(A::reconcile_work(a)) => write!(out, "{}", ReconcileType(a.type_.into())),
        Ok(A::stripe_frag(a)) => write!(out, "nr_empty={}", a.nr_empty),
        Ok(A::dev_stripe_frag(a)) => write!(out, "dev={}", a.dev),
        Ok(A::dev_leaving(a)) => {
            let dev = a.dev;
            let rcu = rcu::read_lock();
            match fs.and_then(|fs| fs.dev_rcu(dev, &rcu)) {
                Some(ca) => write!(out, "{} ", ca.name().to_str().unwrap_or("?")),
                None => write!(out, "{dev} "),
            };
        }
        Ok(A::nr_inodes(_) | A::rebalance_work(_) | A::inum(_)) => {}
    }
}

impl BkeyOps for c::Accounting {
    fn validate(v: &BkeyValidate<'_, '_>) -> Result<(), BchError> {
        use DiskAccountingPosRef as A;

        let pos = DiskAccountingPos::from_bpos(v.k.k.p);
        let arm = match pos.get() {
            Err(ArmError::Unknown(_)) => return Ok(()),
            arm => arm,
        };

        let ver = v.k.k.bversion;
        bkey_fsck_err_on!(v, v.from.flags().contains(bch_validate_flags::BCH_VALIDATE_commit) &&
                          ver.hi == 0 && ver.lo == 0,
                          id::accounting_key_version_0, "accounting key with version=0")?;

        let arm = match arm {
            Ok(arm) => arm,
            Err(ArmError::Bad { err, .. }) => {
                return Err(match replicas_past_end(err) {
                    Some((devs, room)) => bkey_fsck_err!(v, id::accounting_key_replicas_past_end,
                        "accounting key replicas entry with {devs} devs, room for {room}"),
                    None => bkey_fsck_err!(v, id::accounting_key_replicas_past_end,
                        "accounting key replicas entry: {err}"),
                });
            }
            Err(ArmError::Unknown(_) | ArmError::Short(_)) => unreachable!("Unknown returned above, and only a size: arm union is Short"),
        };

        if let A::replicas(r) = arm {
            bkey_fsck_err_on!(v, r.nr_devs == 0, id::accounting_key_replicas_nr_devs_0,
                              "accounting key replicas entry with nr_devs=0")?;
            bkey_fsck_err_on!(v, r.nr_required > r.nr_devs || (r.nr_required > 1 && r.nr_required == r.nr_devs),
                              id::accounting_key_replicas_nr_required_bad,
                              "accounting key replicas entry with bad nr_required")?;
            bkey_fsck_err_on!(v, r.devs.windows(2).any(|d| u32::from(d[0]) != c::BCH_SB_MEMBER_INVALID && d[0] >= d[1]),
                              id::accounting_key_replicas_devs_unsorted,
                              "accounting key replicas entry with unsorted devs")?;
        }

        let end = match arm {
            A::inum(_) | A::dev_leaving(_) => BPOS_SIZE,
            arm => DiskAccountingPos::ARMS_AT + arm.len(),
        };

        bkey_fsck_err_on!(v, pos.as_bytes()[end..].iter().any(|&b| b != 0),
                          id::accounting_key_junk_at_end, "junk at end of accounting key")?;

        let nr_counters = v.k.arm::<Accounting>().expect("an accounting key").v().d.len();
        bkey_fsck_err_on!(v, nr_counters == 0 || nr_counters > MAX_COUNTERS,
                          id::accounting_key_nr_counters_wrong,
                          "accounting key with {nr_counters} counters, should be {}", pos.nr_counters())
    }

    #[cold]
    fn to_text(out: &mut Printbuf, fs: Option<&Fs>, k: BkeySC<'_>) {
        key_to_text(out, fs, &DiskAccountingPos::from_bpos(k.k.p));
        write!(out, " {}", Join(" ", k.arm::<Accounting>().expect("an accounting key").v().d.iter().map(|&d| d as i64)));
    }

    fn swab(_fs: Option<&Fs>, mut k: BkeyS<'_>) {
        for d in k.val_bytes_mut().chunks_exact_mut(size_of::<u64>()) {
            d.reverse();
        }
    }
}

fn normalized_bpos(pos: &DiskAccountingPos) -> Bpos {
    match pos.get() {
        Ok(DiskAccountingPosRef::replicas(r)) => {
            let mut devs = [0u8; BPOS_SIZE];
            let devs = &mut devs[..r.devs.len()];
            devs.copy_from_slice(&r.devs);
            devs.sort_unstable();
            replicas_acct(DataType(r.data_type.into()), r.nr_required, devs).to_bpos()
        }
        _ => pos.to_bpos(),
    }
}

pub(crate) fn mod_normal(t: &TransAttempt<'_, '_>, pos: &DiskAccountingPos, d: &[u64]) -> Result<(), BchError> {
    let p = normalized_bpos(pos);

    let keys = unsafe { t.subbuf(Subbuf::Accounting) };
    let queued = VstructRefEntriesMut::<format::bkey_i>::new(keys.as_mut_bytes()).with_offsets().find_map(|(at, k)| {
        let mut k = k.expect("the transaction's accounting keys");
        let k = k.key_mut();
        if k.k.p != p {
            return None;
        }

        let at = at / size_of::<u64>();
        let range = at..at + usize::from(k.k.u64s);
        let counters = &mut k.arm::<Accounting>().expect("an accounting key").v_mut().d;
        (counters.len() == d.len()).then(|| {
            for (c, &d) in counters.iter_mut().zip(d) {
                *c = c.wrapping_add(d);
            }
            (range, counters.iter().all(|&c| c == 0))
        })
    });

    match queued {
        Some((range, true)) => t.subbuf_remove(Subbuf::Accounting, range),
        Some(_) => {}
        None => {
            let k = t.subbuf_alloc(Subbuf::Accounting, BKEY_U64S + d.len())?;
            k[..BKEY_U64S].as_mut_bytes().copy_from_slice(plain_bytes(&accounting_bkey(p, d.len())));
            k[BKEY_U64S..].copy_from_slice(d);
        }
    }
    Ok(())
}

fn update_sb_one(fs: &Fs, p: Bpos) -> Result<(), BchError> {
    replicas_entry(&DiskAccountingPos::from_bpos(p)).map_or(Ok(()), |e| fs.mark_replicas(e))
}

fn mod_gc(t: &TransAttempt<'_, '_>, pos: &DiskAccountingPos, d: &[u64]) -> Result<(), BchError> {
    let fs = t.fs();
    let p = normalized_bpos(pos);
    let a = Delta { p, d };

    loop {
        let r = {
            let mut mark = fs.mark_lock().read();
            accounting_mem::mem_add(fs, a, true, &mut mark)
        };
        match r {
            Err(e) if e.matches(bch_errcode::BCH_ERR_btree_insert_need_mark_replicas) =>
                t.drop_locks_do(|| update_sb_one(fs, p))?,
            r => return r.map(|_| ()),
        }
    }
}

pub fn add<A: KeyType>(t: &TransAttempt<'_, '_>, arm: A, d: A::Delta, gc: bool) -> Result<(), BchError> {
    d.with_slice(|d| add_at(t, &DiskAccountingPos::from_arm(arm), d, gc))
}

pub fn read<A: KeyType>(fs: &Fs, arm: A) -> A::Read {
    A::Read::from_slice(&mem_read(fs, &DiskAccountingPos::from_arm(arm)))
}

pub(crate) fn read_locked<A: KeyType>(fs: &Fs, mark: &impl MarkHeld, arm: A) -> A::Read {
    A::Read::from_slice(&mem_read_locked(fs, mark, &DiskAccountingPos::from_arm(arm)))
}

pub fn add_at(t: &TransAttempt<'_, '_>, pos: &DiskAccountingPos, d: &[i64], gc: bool)
    -> Result<(), BchError>
{
    let ty = pos.type_().0 as usize;
    assert!(d.len() <= MAX_COUNTERS && ty < TYPE_NR, "accounting update of type {ty} with {} counters", d.len());
    debug_assert_eq!(d.len(), pos.nr_counters());

    let d = <[u64]>::ref_from_bytes(d.as_bytes()).expect("i64s are u64s");
    if gc { mod_gc(t, pos, d) } else { mod_normal(t, pos, d) }
}

#[c_export]
pub unsafe fn bch2_disk_accounting_mod<'t>(trans: &'t BtreeTrans<'t>, k: &DiskAccountingPos,
                                           d: *const i64, nr: c_uint, gc: bool) -> c_int {
    let (t, d) = unsafe { (trans.attempt_in_progress(), slice::from_raw_parts(d, nr as usize)) };
    ret_to_c(add_at(&t, k, d, gc))
}

/*
 * Ensure accounting keys being updated are present in the superblock, when
 * applicable (i.e. replicas updates)
 */
#[c_export]
pub unsafe fn bch2_accounting_update_sb<'t>(trans: &'t BtreeTrans<'t>) -> c_int {
    let t = unsafe { trans.attempt_in_progress() };
    let keys = unsafe { t.subbuf(Subbuf::Accounting) };
    ret_to_c(VstructRefEntries::<format::bkey_i>::new(keys.as_bytes()).try_for_each(|k| {
        update_sb_one(t.fs(), k.expect("the transaction's accounting keys").key().k.p)
    }))
}

pub fn mod_dev_cached_sectors(t: &TransAttempt<'_, '_>, dev: u32, sectors: i64, gc: bool)
    -> Result<(), BchError>
{
    add_at(t, &replicas_acct(DataType::cached, 1, &[dev as u8]), &[sectors], gc)
}

/// Snapshot @id's counters - keys, key bytes, sectors - in each snapshotted
/// btree. In memory, so current without a write buffer flush.
pub fn snapshot_btrees(fs: &Fs, id: u32) -> impl Iterator<Item = SnapshotCounters> + '_ {
    crate::btrees_in(crate::BTREE_HAS_SNAPSHOTS_MASK).map(move |btree| read(fs, Snapshot { id, btree: btree.0 }))
}

pub fn nr_inodes(fs: &Fs) -> u64 {
    read(fs, NrInodes {}).nr
}

pub fn accumulate(dst: &mut BkeyI, src: BkeySC<'_>) {
    let s = &src.arm::<Accounting>().expect("an accounting key").v().d;
    for (d, s) in dst.arm::<Accounting>().expect("an accounting key").v_mut().d.iter_mut().zip(s) {
        *d = d.wrapping_add(*s);
    }

    let (dv, sv) = (dst.k.bversion, src.k.bversion);
    if dv < sv {
        dst.k.bversion = sv;
    }
}

impl Fs {
    /// Device @ca's usage accounting, deleted: as it's removed.
    pub fn dev_usage_remove(&self, ca: &Dev) -> Result<(), BchError> {
        let trans = btree_trans!(self);
        let at = |data_type| DiskAccountingPos::from_arm(DevDataType { dev: ca.dev_idx, data_type }).to_bpos();
        let (start, end) = (at(0), at(u8::MAX));

        trans.write_buffer_flush_sync()?;
        commit_do(&trans, None, CommitFlags::empty(), |t| {
            let mut iter = BtreeIter::new(t, format::Btree::accounting, start, BtreeIterFlags::ALL_SNAPSHOTS);
            iter.for_each_max_norestart(t, end, |_, k| {
                let Some(a) = k.arm::<Accounting>() else { return Ok(LoopFlow::Continue) };
                if let Ok(DiskAccountingPosRef::dev_data_type(arm)) = DiskAccountingPos::from_bpos(k.k.p).get() {
                    let d = DevDataTypeCounters::<u64>::from_slice(&a.v().d).map(|v| (v as i64).wrapping_neg());
                    add(t, *arm, d, false)?;
                }
                Ok(LoopFlow::Continue)
            })
        })?;
        trans.write_buffer_flush_sync()
    }
}

pub fn dev_usage_init(ca: &Dev, gc: bool) -> Result<(), BchError> {
    let fs = ca.fs();
    let trans = btree_trans!(fs);
    bch_err_fn!(fs, lockrestart_do(&trans, |t| {
        /*
         * Set, not add: subtract whatever's currently accounted so the
         * free count lands at exactly nbuckets. This makes
         * dev_usage_init idempotent, so it's safe to re-run when a
         * half-finished device add is resumed during recovery.
         *
         * gc accounting is rebuilt from a cleared state, and the read only
         * sees the non-gc counters, so the gc path keeps the plain
         * delta-add (cur stays zero).
         */
        let arm = DevDataType { dev: ca.dev_idx, data_type: DataType::free.0 as u8 };
        let cur = if gc { DevDataTypeCounters::default() } else { read(fs, arm) };
        let mi = ca.mi.get();
        let nbuckets = mi.nbuckets.wrapping_sub(mi.first_bucket.into());

        add(t, arm, DevDataTypeCounters {
            buckets:    nbuckets.wrapping_sub(cur.buckets) as i64,
            sectors:    cur.sectors.wrapping_neg() as i64,
            fragmented: cur.fragmented.wrapping_neg() as i64,
        }, gc)?;
        if !gc {
            t.commit(None, CommitFlags::empty())?;
        }
        Ok(())
    }))
}

#[c_export]
pub fn bch2_dev_usage_init(ca: &Dev, gc: bool) -> c_int {
    ret_to_c(dev_usage_init(ca, gc))
}

#[c_export]
pub fn bch2_verify_accounting_clean(fs: &Fs) {
    let mut mismatch = false;
    let mut base = bch_fs_usage_base::default();

    let trans = btree_trans!(fs);
    let mut iter = BtreeIter::new(&trans, format::Btree::accounting, POS_MIN, BtreeIterFlags::ALL_SNAPSHOTS);
    let _ = iter.for_each(&trans, |_, _, k| {
        let Some(a) = k.arm::<Accounting>() else { return Ok(LoopFlow::Continue) };
        let d = &a.v().d;
        let nr = d.len();

        let acc_k = DiskAccountingPos::from_bpos(k.k.p);
        if matches!(acc_k.get(), Err(ArmError::Unknown(_))) {
            return Ok(LoopFlow::Break(()));
        }

        if !is_mem(&acc_k) {
            return Ok(LoopFlow::ContinueFrom(acc_k.next_type_start()));
        }

        let v = mem_read(fs, &acc_k);
        if d[..] != v[..nr] {
            log_no_fs(LogLevel::ERR, message!("{} != {}", k.to_text(fs), Join(" ", v[..nr].iter())));
            mismatch = true;
        }

        let (u, inmem) = usage_of(fs, &acc_k, d, |c| c.map(|c| c.sum()));
        base = base.wrapping_add(u);
        if let Some(v) = inmem.filter(|v| d[..] != v[..]) {
            log_no_fs(LogLevel::ERR, message!("dev accounting mismatch: {} in mem {}",
                                             k.to_text(fs), Join(" ", v[..nr].iter())));
            mismatch = true;
        }
        Ok(LoopFlow::Continue)
    });

    let base_inmem = percpu_field!(fs.capacity.pcpu.get(), counters.usage).sum();
    for (name, base, inmem) in [("hidden",   base.hidden,   base_inmem.hidden),
                                ("btree",    base.btree,    base_inmem.btree),
                                ("data",     base.data,     base_inmem.data),
                                ("cached",   base.cached,   base_inmem.cached),
                                ("reserved", base.reserved, base_inmem.reserved)] {
        if base != inmem {
            log_no_fs(LogLevel::ERR, message!("fs_usage_base.{name} mismatch: {base} != {inmem}"));
            mismatch = true;
        }
    }

    crate::warn_on!(mismatch);
}
