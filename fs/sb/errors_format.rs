/*
 * v2 entries add the time of first occurrence: id (16 bits), a
 * saturating occurrence count (32), and two 40-bit second-resolution
 * timestamps - good until the year ~36,800 - packed exactly into 128
 * bits. No 64-bit boundary partition fits {16, 32, 40, 40}, so
 * last_error_time spans the two words: in Rust the entry is one
 * little-endian u128, where the fields are contiguous; C has the two
 * words and hand-rolled accessors, whose setters saturate, since a
 * wrapped count or timestamp would be worse than a pinned one.
 *
 * v[0]: id 0..16, nr 16..48, last_error_time 48..64 (low 16 bits)
 * v[1]: last_error_time 0..24 (high 24 bits), first_error_time 24..64
 */
/* align(8): C's v is __le64 v[2]; its bitfield's le::U128 is aligned to 1 */
nest! {
    #[repr(C, align(8))]
    #[derive(Clone, Copy, Default, CStruct, Plain, TypeInfo)]
    #[c_typedef(bch_sb_field_error_entry_v2)]
    pub struct bch_sb_field_error_entry_v2 {
        #[c("__le64 v[2]")]
        #>[bitfield(u128, repr = le::U128, from = le::U128::new, into = le::U128::get)]
        pub v: pub struct bch_sb_field_error_entry_v2_bits {
            id:               u16,
            nr:               u32,
            last_error_time:  u40,
            first_error_time: u40,
        },
    }
}

#[unsized_vstruct]
#[repr(C)]
#[derive(Clone, Copy, Default, CStruct, Plain, TypeInfo)]
pub struct bch_sb_field_errors_v2 {
    pub field: Head<c::bch_sb_field>,
    pub entries: [c::bch_sb_field_error_entry_v2; 0],
}
